namespace Autonogrammer.Sessions.Postgres.Migrations;

/// <summary>M0005: the dispatch command log, the user feed and the audit. <c>dispatch_commands</c> is a regular table because its rows move through a state machine. <c>dispatch_events</c> and <c>dispatch_audit</c> are hypertables; the audit table keeps only the keyed tenant hash of the account, never the account identifier, and the runtime role may only insert into it and read it (the role grants are in <c>deploy/data-plane/bootstrap.sql</c>, and this step revokes the rest when the role exists). The per-device <c>seq</c> is assigned under the <c>dispatch_devices</c> row lock and the per-account feed <c>id</c> under the <c>accounts</c> row lock.</summary>
internal sealed class M0005_Dispatch : IMigrationStep
{
    private const string Up = """
        CREATE TABLE IF NOT EXISTS dispatch_devices (
            id text PRIMARY KEY,
            account_id text NOT NULL,
            name text NOT NULL,
            platform text NOT NULL,
            public_key text NOT NULL,
            created_at timestamptz NOT NULL,
            last_seen_at timestamptz NULL,
            revoked_at timestamptz NULL,
            command_seq bigint NOT NULL DEFAULT 0
        );
        CREATE INDEX IF NOT EXISTS dispatch_devices_account_idx ON dispatch_devices (account_id);
        CREATE TABLE IF NOT EXISTS dispatch_commands (
            id text PRIMARY KEY,
            device_id text NOT NULL,
            account_id text NOT NULL,
            seq bigint NOT NULL,
            op text NOT NULL,
            state text NOT NULL,
            idempotency_key text NOT NULL,
            expires_at timestamptz NOT NULL,
            body jsonb NULL,
            body_purged_at timestamptz NULL,
            result jsonb NULL,
            created_at timestamptz NOT NULL,
            updated_at timestamptz NOT NULL,
            CONSTRAINT dispatch_commands_device_seq_uq UNIQUE (device_id, seq),
            CONSTRAINT dispatch_commands_idempotency_uq UNIQUE (account_id, device_id, idempotency_key)
        );
        CREATE INDEX IF NOT EXISTS dispatch_commands_account_idx ON dispatch_commands (account_id);
        CREATE TABLE IF NOT EXISTS dispatch_events (
            account_id text NOT NULL,
            id bigint NOT NULL,
            occurred_at timestamptz NOT NULL,
            kind text NOT NULL,
            ref text NULL,
            payload jsonb NULL,
            PRIMARY KEY (account_id, id, occurred_at)
        );
        SELECT create_hypertable('dispatch_events', 'occurred_at', chunk_time_interval => INTERVAL '1 day', if_not_exists => TRUE);
        CREATE TABLE IF NOT EXISTS dispatch_audit (
            account_id_hash text NOT NULL,
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            occurred_at timestamptz NOT NULL,
            device_id text NULL,
            command_id text NULL,
            op text NOT NULL,
            outcome text NOT NULL,
            corr text NULL,
            PRIMARY KEY (account_id_hash, id, occurred_at)
        );
        SELECT create_hypertable('dispatch_audit', 'occurred_at', chunk_time_interval => INTERVAL '7 days', if_not_exists => TRUE);
        DO $revoke$
        BEGIN
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'autonogrammer_app') THEN
                REVOKE UPDATE, DELETE, TRUNCATE ON dispatch_audit FROM autonogrammer_app;
            END IF;
        END
        $revoke$;
        """;

    private const string Down = """
        DROP TABLE IF EXISTS dispatch_audit;
        DROP TABLE IF EXISTS dispatch_events;
        DROP TABLE IF EXISTS dispatch_commands;
        DROP TABLE IF EXISTS dispatch_devices;
        """;

    /// <inheritdoc />
    public int Version => 5;

    /// <inheritdoc />
    public string Name => "dispatch";

    /// <inheritdoc />
    public string UpSql => Up;

    /// <inheritdoc />
    public string DownSql => Down;
}
