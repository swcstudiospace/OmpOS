    /// <summary>Builds the row of one token.</summary>
    private static SlashCommandDescriptor Make(
        string name,
        SlashCommandGroup group,
        string description,
        SlashHandlerKind kind,
        SlashCommandStatus status,
        string handlerId,
        string hint,
        string note,
        string? actionArgument,
        string? engineCommand,
        string? aliasOf)
    {
        var unavailable = status == SlashCommandStatus.Unavailable;
        return new SlashCommandDescriptor
        {
            Name = name,
            Description = description,
            Arguments = ParseArguments(hint),
            Platforms = kind == SlashHandlerKind.NativeAction ? DesktopPlatforms : DesktopPlatforms | CommandPlatforms.Ios | CommandPlatforms.Android | CommandPlatforms.Web,
            DisabledReason = unavailable ? note : null,
            HandlerId = handlerId,
            Kind = kind,
            Status = status,
            Group = group,
            ActionArgument = actionArgument,
            EngineCommand = engineCommand,
            AliasOf = aliasOf,
            Note = unavailable ? null : note,
        };
    }

    /// <summary>Reads an argument hint such as <c>[filter]</c> or <c>&lt;models&gt; &lt;task&gt;</c> into arguments: square brackets mark an optional argument, angle brackets a required one.</summary>
    private static SlashCommandArgument[] ParseArguments(string hint)
    {
        if (hint.Length == 0)
        {
            return [];
        }

        return
        [
            .. hint.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(static word => new SlashCommandArgument
            {
                Name = word.Trim(HintBrackets),
                IsRequired = word[0] == '<',
                Description = "The " + word.Trim(HintBrackets) + ".",
            }),
        ];
    }
