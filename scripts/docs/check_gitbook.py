#!/usr/bin/env python3
"""Offline structure check of the OmpOS documentation for GitBook Git Sync (standard library only).

Usage: check_gitbook.py [repository-root] [--require-screenshots] [--list-outside-root]

The repository root is the directory that holds `.gitbook.yaml` (default: the repository this script lives in).
Exit status 1 when any ERROR is reported. Checks:

  * `.gitbook.yaml`: `root`, `structure.readme` and `structure.summary` resolve to existing files;
  * `SUMMARY.md` grammar (headings and `* [Title](path.md)` items, indentation steps of one level), every entry
    resolves to a file inside the root, no file is listed twice;
  * no orphan: every `.md` under the root is listed in SUMMARY.md unless it is under an ignored tree (IGNORED_TREES);
  * every listed page: front matter closed, `description:` quoted, exactly one H1 outside code fences, a `Status:` line
    near the top (except decision records, the open-questions register and generated pages), balanced code fences and
    balanced `{% %}` blocks;
  * every relative link, image and `<img src>`/`<source srcset>` resolves; links with `#anchor` to a Markdown page must
    name a heading of that page; a relative link that leaves the GitBook root is reported as a WARN (it works on GitHub
    and is dead on the published site);
  * the pinned screenshots (SCREENSHOTS) exist: a WARN by default (the release step adds them), an ERROR with
    `--require-screenshots` (the release gate);
  * no file above the 100 MB Git Sync limit.

Design: docs/plans/v0.15.0-research/12-github-gitbook-plan.md section 3.4. No network access, no third-party modules.
"""
import os
import re
import sys

# Trees under the GitBook root that are published by nobody: research, plans, recorded evidence, internal change requests.
IGNORED_TREES = (
    "plans/",
    "runbooks/evidence/",
    "api/",
)

# Pages that are not required to carry a `Status:` line: decision records keep their own Status header,
# the open-questions register is a table of records, generated pages say so in their first lines.
STATUS_EXEMPT_PREFIXES = ("decisions/",)
STATUS_EXEMPT_FILES = (
    "open-questions.md",  # a register of records
    "SUMMARY.md",
    "settings-parity.md",  # owned and regenerated by the Settings work
    "reference/slash-commands.md",  # generated from the slash catalogue; a test parses it
    "quality/cursor-parity-audit-2026-10-26.md",  # frozen previous audit
)

# File names pinned by the documentation task; the release step adds the images.
SCREENSHOTS = (
    "assets/screens/web-agents-light.png",
    "assets/screens/web-agents-dark.png",
    "assets/screens/web-kanban-light.png",
    "assets/screens/web-settings-models-light.png",
    "assets/screens/web-changes-review-light.png",
    "assets/screens/web-mobile-light.png",
    "assets/screens/desktop-agents-light.png",
    "assets/screens/desktop-settings-light.png",
)

MAX_BYTES = 100 * 1024 * 1024
STATUS_WINDOW = 15  # the Status: line must appear within this many lines after the H1

errors = []
warns = []


def err(message):
    errors.append(message)


def warn(message):
    warns.append(message)


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def slug(heading):
    """GitHub/GitBook-style heading slug: lower case, markup dropped, punctuation dropped, spaces to hyphens."""
    heading = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    heading = re.sub(r"[`*_]|<[^>]+>", "", heading).strip().lower()
    return re.sub(r"\s", "-", re.sub(r"[^\w\s-]", "", heading))


def strip_fences(text):
    """Remove fenced code blocks (``` or ~~~) and inline code so their content is never parsed as Markdown."""
    text = re.sub(r"^(```|~~~).*?^\1[^\n]*$", "", text, flags=re.S | re.M)
    return re.sub(r"`[^`\n]*`", "``", text)


def parse_config(base):
    cfg = {"root": "./", "readme": "README.md", "summary": "SUMMARY.md"}
    path = os.path.join(base, ".gitbook.yaml")
    if not os.path.isfile(path):
        err(".gitbook.yaml is missing in " + base)
        return cfg
    section = None
    for line in read(path).splitlines():
        stripped = line.split("#", 1)[0].rstrip()
        if not stripped.strip():
            continue
        match = re.match(r"^(\s*)([A-Za-z_]+):\s*(.*)$", stripped)
        if not match:
            warn(".gitbook.yaml: cannot parse line: " + stripped)
            continue
        indent, key, value = len(match.group(1)), match.group(2), match.group(3).strip().strip("\"'")
        if indent == 0:
            section = key
            if key == "root" and value:
                cfg["root"] = value
            elif key not in ("root", "structure", "redirects"):
                warn(".gitbook.yaml: unknown top-level key " + key)
        elif section == "structure" and key in ("readme", "summary") and value:
            cfg[key] = value
    return cfg


def parse_summary(summary, root):
    """Return {absolute path: line number} of every SUMMARY entry and report grammar errors."""
    item = re.compile(r"^(\s*)[*-]\s+\[([^\]]*)\]\(([^)\s]*)(?:\s+\"([^\"]*)\")?\)\s*$")
    listed = {}
    unit = None
    previous = 0
    for number, line in enumerate(read(summary).splitlines(), 1):
        if not line.strip():
            continue
        if re.match(r"^#{1,6}\s", line):
            previous = 0
            continue
        match = item.match(line)
        if not match:
            err("SUMMARY.md:%d: not a heading or a `* [Title](path.md)` item: %s" % (number, line.strip()[:70]))
            continue
        width = len(match.group(1).replace("\t", "    "))
        if width and unit is None:
            unit = width
        if width and unit and width % unit:
            err("SUMMARY.md:%d: indentation %d is not a multiple of %d" % (number, width, unit))
        level = width // unit if unit else 0
        if level - previous > 1:
            err("SUMMARY.md:%d: nesting jumps more than one level" % number)
        previous = level
        target = match.group(3)
        if re.match(r"^[a-z][a-z0-9+.-]*://", target, re.I) or not target.split("#")[0]:
            continue
        full = os.path.normpath(os.path.join(os.path.dirname(summary), target.split("#")[0]))
        if full in listed:
            err("SUMMARY.md:%d: %s is already listed at line %d (a page may appear once)" % (number, target, listed[full]))
        listed[full] = number
        if not os.path.isfile(full):
            err("SUMMARY.md:%d: missing file %s" % (number, target))
        elif not full.startswith(root + os.sep):
            err("SUMMARY.md:%d: %s is outside the root" % (number, target))
    return listed


def ignored(rel_to_root):
    rel = rel_to_root.replace(os.sep, "/")
    return any(rel.startswith(tree) for tree in IGNORED_TREES)


def check_page(path, root, base, listed, summary, headings_cache, strict=True):
    rel = os.path.relpath(path, base)
    rel_root = os.path.relpath(path, root).replace(os.sep, "/")
    text = read(path)
    lines = text.split("\n")
    body_start = 0
    if strict and lines and lines[0].strip() == "---":
        closing = [i for i, value in enumerate(lines[1:], 1) if value.strip() == "---"]
        if not closing:
            err(rel + ": front matter is not closed")
        else:
            body_start = closing[0] + 1
            for value in lines[1 : closing[0]]:
                match = re.match(r"^description:\s*(.*)$", value)
                if match:
                    description = match.group(1).strip()
                    if not (len(description) >= 2 and description[0] == description[-1] and description[0] in "\"'"):
                        err(rel + ": description must be quoted (an unquoted value fails silently in Git Sync): " + value[:60])
                elif re.match(r"^[A-Za-z_]+:\s*[^\"'\s>|\[{-].*(:\s|\s#)", value):
                    err(rel + ": front matter value with `: ` or ` #` must be quoted: " + value[:60])
    if strict and text.count("```") % 2:
        err(rel + ": unbalanced ``` fences")
    stack = []
    for tag in re.findall(r"\{%\s*([a-z-]+)\b", strip_fences(text)) if strict else []:
        if tag.startswith("end"):
            if not stack or stack.pop() != tag[3:]:
                err(rel + ": {% " + tag + " %} has no matching opener")
        elif tag not in ("else", "elsif", "include", "embed", "openapi", "openapi-schemas", "openapi-operation"):
            stack.append(tag)
    if stack:
        err(rel + ": unclosed {% " + stack[-1] + " %}")
    body = strip_fences("\n".join(lines[body_start:]))
    h1s = re.findall(r"^#\s+(.*\S)\s*$", body, flags=re.M)
    if strict and len(h1s) != 1:
        err("%s: expected exactly one H1, found %d" % (rel, len(h1s)))
    in_summary = path in listed or path == summary
    if strict and in_summary and rel_root not in STATUS_EXEMPT_FILES and not rel_root.startswith(STATUS_EXEMPT_PREFIXES):
        head = body.split("\n")
        first = next((i for i, value in enumerate(head) if re.match(r"^#\s", value)), None)
        window = head[(first or 0) : (first or 0) + STATUS_WINDOW + 1]
        generated = "Generated by" in "\n".join(head[:12])
        if not generated and not any(re.match(r"^\**Status:\**\s*\S", value) for value in window):
            err(rel + ": no `Status:` line within %d lines of the H1" % STATUS_WINDOW)
    anchors = headings_cache.setdefault(path, {slug(h) for h in re.findall(r"^#{1,6}\s+(.*\S)\s*$", body, flags=re.M)})
    link = re.compile(r"(!?)\[[^\]]*\]\(<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\)")
    html = re.compile(r"<(?:img|source|a)\b[^>]*?(?:src|srcset|href)=\"([^\"]+)\"")
    targets = [m.group(2) for m in link.finditer(body)] + html.findall(body)
    for target in targets:
        if re.match(r"^([a-z][a-z0-9+.-]*:|//)", target, re.I):
            continue
        target_path, _, fragment = target.partition("#")
        target_path = target_path.split("?")[0]
        if not target_path:
            if fragment and slug(fragment) not in anchors and fragment not in anchors:
                err("%s: anchor #%s not found in the page" % (rel, fragment))
            continue
        if target_path.startswith("/"):
            full = os.path.normpath(os.path.join(root, target_path.lstrip("/")))
        else:
            full = os.path.normpath(os.path.join(os.path.dirname(path), target_path))
        if not os.path.exists(full):
            repo_rel = os.path.relpath(full, base).replace(os.sep, "/")
            if repo_rel in SCREENSHOTS_REPO:
                continue  # reported once by the screenshot check
            err("%s: broken link or image %s" % (rel, target))
            continue
        if not (full == root or full.startswith(root + os.sep)):
            outside.append("%s: %s leaves the GitBook root (dead link on the published site; use a GitHub URL)" % (rel, target))
        if fragment and full.endswith(".md") and os.path.isfile(full):
            if full not in headings_cache:
                other = strip_fences(read(full))
                headings_cache[full] = {slug(h) for h in re.findall(r"^#{1,6}\s+(.*\S)\s*$", other, flags=re.M)}
            if slug(fragment) not in headings_cache[full] and fragment not in headings_cache[full]:
                err("%s: anchor #%s not found in %s" % (rel, fragment, target_path))


outside = []
SCREENSHOTS_REPO = set()


def main(argv):
    require_screenshots = "--require-screenshots" in argv
    list_outside = "--list-outside-root" in argv
    positional = [a for a in argv if not a.startswith("--")]
    default_base = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    base = os.path.abspath(positional[0] if positional else default_base)
    cfg = parse_config(base)
    root = os.path.normpath(os.path.join(base, cfg["root"]))
    if not os.path.isdir(root):
        err("root directory missing: " + root)
        return finish(base, 0, 0)
    readme = os.path.normpath(os.path.join(root, cfg["readme"]))
    summary = os.path.normpath(os.path.join(root, cfg["summary"]))
    if not os.path.isfile(readme):
        err("landing page missing: " + os.path.relpath(readme, base))
    if not os.path.isfile(summary):
        err("SUMMARY.md missing: " + os.path.relpath(summary, base))
        return finish(base, 0, 0)
    listed = parse_summary(summary, root)

    md_files = []
    for directory, subdirs, files in os.walk(root):
        subdirs[:] = [d for d in subdirs if d not in (".git", "node_modules")]
        for name in files:
            full = os.path.join(directory, name)
            if os.path.getsize(full) > MAX_BYTES:
                err("over the 100 MB Git Sync file limit: " + os.path.relpath(full, base))
            if name.lower().endswith(".md"):
                md_files.append(full)
    for full in sorted(md_files):
        rel_root = os.path.relpath(full, root).replace(os.sep, "/")
        if full not in listed and full != readme and full != summary and not ignored(rel_root):
            err("orphan page (not in SUMMARY.md and not in an ignored tree): " + os.path.relpath(full, base))
    if readme in listed:
        err("README.md is the landing page (structure.readme) and must not be listed in SUMMARY.md")

    for shot in SCREENSHOTS:
        full = os.path.join(root, shot)
        SCREENSHOTS_REPO.add(os.path.relpath(full, base).replace(os.sep, "/"))
        if not os.path.isfile(full):
            message = "pinned screenshot missing: " + os.path.relpath(full, base)
            if require_screenshots:
                err(message)
            else:
                warn(message + " (the release step adds it; --require-screenshots makes this an error)")

    cache = {}
    pages = [readme, summary] + sorted(listed)
    for page in pages:
        if os.path.isfile(page):
            check_page(page, root, base, listed, summary, cache)
    landing = os.path.join(base, "README.md")
    if os.path.isfile(landing):
        outside_before = len(outside)
        check_page(landing, root, base, listed, summary, cache, strict=False)
        del outside[outside_before:]  # the repository README lives outside the GitBook root by design
    if list_outside:
        for line in outside:
            warn(line)
    elif outside:
        warn("%d relative links leave the GitBook root (rerun with --list-outside-root to list them)" % len(outside))
    return finish(base, len(md_files), len(listed))


def finish(base, pages, listed):
    for message in warns:
        print("WARN ", message)
    for message in errors:
        print("ERROR", message)
    print("%d markdown files, %d listed in SUMMARY.md, %d errors, %d warnings" % (pages, listed, len(errors), len(warns)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
